#[test]
fn test_template_function_parsing() {
    let source = "template <typename T> T max(T a, T b) { return a > b ? a : b; }";
    let ir = cpp_rust_transpiler::parser::cpp::parse(source).unwrap();
    assert_eq!(ir.items.len(), 1);
    match &ir.items[0] {
        cpp_rust_transpiler::ir::Item::Function(f) => {
            assert_eq!(f.name, "max");
            assert_eq!(f.generics.len(), 1);
            assert_eq!(f.generics[0].name, "T");
        }
        _ => panic!("expected Function"),
    }
}

