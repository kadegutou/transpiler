#[test]
fn test_cpp_type_mapping() {
    use cpp_rust_transpiler::ir::{Mutability, Type};
    use cpp_rust_transpiler::parser::cpp::cpp_type_to_ir;

    assert_eq!(cpp_type_to_ir("void").unwrap(), Type::Unit);
    assert_eq!(
        cpp_type_to_ir("std::vector<int>").unwrap(),
        Type::Named("Vec".to_string(), vec![Type::Named("int".to_string(), vec![])])
    );
    assert_eq!(
        cpp_type_to_ir("const int&").unwrap(),
        Type::Ref(
            Box::new(Type::Named("int".to_string(), vec![])),
            Mutability::Not
        )
    );
}

