#[test]
fn test_namespace_unwrapping() {
    let source = "namespace math { int add(int a, int b) { return a + b; } }";
    let ir = cpp_rust_transpiler::parser::cpp::parse(source).unwrap();
    assert!(!ir.items.is_empty());
    match &ir.items[0] {
        cpp_rust_transpiler::ir::Item::Function(f) => {
            assert_eq!(f.name, "add");
        }
        _ => panic!("expected Function, got: {:?}", ir.items[0]),
    }
}

#[test]
fn test_generic_type_parsing() {
    use cpp_rust_transpiler::parser::cpp::cpp_type_to_ir;
    use cpp_rust_transpiler::ir::Type;

    // queue<int> should parse as Named("Queue", [Named("int", [])])
    let t = cpp_type_to_ir("queue<int>").unwrap();
    assert_eq!(
        t,
        Type::Named("Queue".to_string(), vec![Type::Named("int".to_string(), vec![])])
    );

    // map<int, string> should parse generically (string maps to String)
    let t = cpp_type_to_ir("map<int, string>").unwrap();
    assert_eq!(
        t,
        Type::Named("map".to_string(), vec![
            Type::Named("int".to_string(), vec![]),
            Type::Named("String".to_string(), vec![]),
        ])
    );

    // Verify int maps to i64 in pipeline
    assert_eq!(
        cpp_type_to_ir("int").unwrap(),
        Type::Named("int".to_string(), vec![])
    );
}

#[test]
fn test_pipeline_template_function() {
    let source = "template <typename T> T max(T a, T b) { return a > b ? a : b; }";
    let result = transpile(source, Direction::CppToRust).unwrap();
    assert!(result.contains("fn max<T>"));
    assert!(result.contains("a: T"));
    assert!(result.contains("b: T"));
    assert!(result.contains("-> T"));
}

